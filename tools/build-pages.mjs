// Builds one real page per section of the site, plus sitemap.xml.
// Edit site-src/index.html, then run:  node tools/build-pages.mjs
// Output (committed): index.html, <section>.html (served at /<section>), sitemap.xml
import { readFileSync, writeFileSync } from 'node:fs';
import { execSync } from 'node:child_process';

const SITE = 'https://www.warriorspiritmuaythai.co.uk';
const src = readFileSync('site-src/index.html', 'utf8');

// split into views
const re = /<div class="view" data-view="([^"]+)"([^>]*)>/g;
const starts = [];
let m;
while ((m = re.exec(src))) starts.push({ key: m[1], at: m.index, tag: m[0] });
const footerAt = src.indexOf('<footer');
const idToView = new Map();
starts.forEach((v, i) => {
  const end = i + 1 < starts.length ? starts[i + 1].at : footerAt;
  const seg = src.slice(v.at, end);
  for (const x of seg.matchAll(/\sid="([^"]+)"/g)) if (!idToView.has(x[1])) idToView.set(x[1], v.key);
  v.title = (v.tag.match(/data-title="([^"]*)"/) || [])[1] || 'Warrior Spirit Muay Thai';
  v.desc = (v.tag.match(/data-desc="([^"]*)"/) || [])[1] || '';
});
const keys = new Set(starts.map(v => v.key));
const urlOf = k => (k === 'home' ? '/' : '/' + k);

function page(v) {
  let out = src.replace(/href="#([^"]*)"/g, (all, name) => {
    if (keys.has(name)) return `href="${urlOf(name)}"`;
    if (idToView.has(name)) return `href="${urlOf(idToView.get(name))}#${name}"`;
    return all;
  });
  const url = SITE + urlOf(v.key);
  out = out.replace(/<title>[^<]*<\/title>/, `<title>${v.title}</title>`)
    .replace(/(<meta name="description" content=")[^"]*(")/, `$1${v.desc}$2`)
    .replace(/(<link rel="canonical" href=")[^"]*(")/, `$1${url}$2`)
    .replace(/(<meta property="og:url" content=")[^"]*(")/, `$1${url}$2`)
    .replace(/(<meta property="og:title" content=")[^"]*(")/, `$1${v.title}$2`)
    .replace(/(<meta property="og:description" content=")[^"]*(")/, `$1${v.desc}$2`);
  // show this section first, hide the home section (scripts then keep it in step)
  out = out.replace(/<div class="view" data-view="([^"]+)"([^>]*?)( hidden)?>/g, (all, k, rest) =>
    `<div class="view" data-view="${k}"${rest}${k === v.key ? '' : ' hidden'}>`);
  out = out.replace('<head>', '<head>\n<!-- GENERATED by tools/build-pages.mjs from site-src/index.html. Do not edit this file. -->');
  return out;
}

for (const v of starts) writeFileSync(v.key === 'home' ? 'index.html' : `${v.key}.html`, page(v));

// sitemap with real last-changed dates (date of the last commit that touched each source)
const day = f => { try { return execSync(`git log -1 --format=%cs -- ${f}`, { encoding: 'utf8' }).trim() || null; } catch { return null; } };
const today = new Date().toISOString().slice(0, 10);
const tpl = day('site-src/index.html') || today;
const list = [
  ...starts.map(v => [urlOf(v.key), tpl]),
  ['/book', day('book.html') || today],
  ['/privacy', day('privacy.html') || today],
  ['/terms', day('terms.html') || today],
  ['/accessibility', day('accessibility.html') || today],
];
writeFileSync('sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
  list.map(([p, d]) => `<url><loc>${SITE}${p}</loc><lastmod>${d}</lastmod></url>`).join('\n') + '\n</urlset>\n');
console.log(`built ${starts.length} pages + sitemap (${list.length} urls)`);
