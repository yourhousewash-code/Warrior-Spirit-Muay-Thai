// Run with: npm test   (Node's built-in test runner; no packages needed)
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, readdirSync } from 'node:fs';
import { checkPhone } from '../api/_lib/phone.js';

test('phone check: UK numbers', () => {
  assert.deepEqual(checkPhone('07904 032142'), { ok: true, mobile: true, value: '07904 032142' });
  assert.deepEqual(checkPhone('+44 7904 032142'), { ok: true, mobile: true, value: '07904 032142' });
  assert.equal(checkPhone('020 7946 0958').mobile, false);
  assert.equal(checkPhone('0790403214').ok, false);
  assert.equal(checkPhone('7904032142').ok, false);
  assert.equal(checkPhone('').ok, false);
});

const pages = readdirSync('.').filter(f => f.endsWith('.html'));
const sections = pages.filter(f => readFileSync(f, 'utf8').includes('GENERATED by tools/build-pages.mjs'));

test('every generated page holds exactly one section, shown', () => {
  assert.ok(sections.length >= 30, `only ${sections.length} generated pages`);
  for (const f of sections) {
    const h = readFileSync(f, 'utf8');
    const views = h.match(/<div class="view" data-view="[^"]+"[^>]*>/g) || [];
    assert.equal(views.length, 1, `${f}: ${views.length} sections`);
    assert.ok(!/\shidden>/.test(views[0]), `${f}: its section is hidden`);
  }
});

test('titles are 60 characters or fewer, and every page has a description and canonical', () => {
  for (const f of sections) {
    const h = readFileSync(f, 'utf8');
    const t = (h.match(/<title>([^<]*)<\/title>/) || [])[1] || '';
    const plain = t.replace(/&amp;/g, '&');
    assert.ok(plain.length > 0 && plain.length <= 60, `${f}: title ${plain.length} characters`);
    assert.match(h, /<meta name="description" content="[^"]{50,}"/, `${f}: description`);
    assert.match(h, /<link rel="canonical" href="https:\/\/www\.warriorspiritmuaythai\.co\.uk\//, `${f}: canonical`);
  }
});

test('nothing about FighterBase on public pages (handbook rule 4)', () => {
  for (const f of pages.filter(f => !['coach.html', 'account.html'].includes(f))) {
    assert.ok(!/fighterbase/i.test(readFileSync(f, 'utf8')), `${f} mentions FighterBase`);
  }
});

test('team and private files stay off the live site', () => {
  const ignore = readFileSync('.vercelignore', 'utf8').split(/\r?\n/).map(s => s.trim());
  for (const x of ['docs', 'handoffs', 'STATUS.md', 'CLAUDE.md', 'parked', 'site-src', 'tools', 'tests']) assert.ok(ignore.includes(x), `.vercelignore is missing ${x}`);
});
